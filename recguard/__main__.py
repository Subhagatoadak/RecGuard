"""`recguard` command line: serve the API, print dev secrets, verify an audit chain."""
from __future__ import annotations
import argparse, json, os, secrets, shlex, sys

DEV_SCOPES={
    'serve':['recommend:serve','metrics:read','audit:read','policy:read'],
    'present':['recommend:present'],
    'event':['telemetry:write'],
    'outcome':['outcomes:write'],
    'learner':['learning:admin'],
    'data':['data:admin'],
    'policy':['policy:write','policy:read'],
}


def dev_env(tenant:str,env_file:str|None=None):
    tokens={secrets.token_urlsafe(32):{'tenant_id':'*' if k=='policy' else tenant,'scopes':v} for k,v in DEV_SCOPES.items()}
    if env_file:
        # Docker Compose reads `.env` beside compose.yaml; single quotes keep the JSON literal.
        if os.path.exists(env_file):sys.exit(f'{env_file} already exists; refusing to overwrite secrets')
        fd=os.open(env_file,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
        with os.fdopen(fd,'w') as f:
            f.write('# DEVELOPMENT ONLY — generated by `recguard dev-env`; never commit or deploy.\n')
            f.write(f"RECGUARD_SIGNING_KEY='{secrets.token_urlsafe(48)}'\n")
            f.write(f"RECGUARD_TOKENS_JSON='{json.dumps(tokens)}'\n")
        print(f'## wrote {env_file}; tokens:')
        for token,info in tokens.items():
            print('#',info['tenant_id'],','.join(info['scopes']),token)
        return
    print('## DEVELOPMENT ONLY — do not use these secrets in a deployed installation.')
    print('export RECGUARD_SIGNING_KEY='+shlex.quote(secrets.token_urlsafe(48)))
    print('export RECGUARD_TOKENS_JSON='+shlex.quote(json.dumps(tokens)))
    print('export RECGUARD_DB='+shlex.quote('recguard-dev.db'))
    print('## token list:')
    for token,info in tokens.items():
        print('#',info['tenant_id'],','.join(info['scopes']),token)


def main(argv=None):
    parser=argparse.ArgumentParser(prog='recguard')
    sub=parser.add_subparsers(dest='cmd',required=True)
    s=sub.add_parser('serve',help='run the HTTP API (needs the `server` extra)')
    s.add_argument('--host',default='127.0.0.1');s.add_argument('--port',type=int,default=8765)
    d=sub.add_parser('dev-env',help='print throwaway local secrets');d.add_argument('--tenant',default='demo')
    d.add_argument('--env-file',help='write a Docker Compose .env file instead of export lines')
    a=sub.add_parser('audit',help='verify a tenant audit chain in a database file')
    a.add_argument('tenant');a.add_argument('--db',default=os.getenv('RECGUARD_DB','recguard.db'))
    a.add_argument('--expected-head')
    pol=sub.add_parser('policy',help='work with YAML/JSON policy packs')
    psub=pol.add_subparsers(dest='policy_cmd',required=True)
    v=psub.add_parser('validate',help='check schema, expression syntax and names (no context values needed)')
    v.add_argument('files',nargs='+')
    sh=psub.add_parser('show',help='print the resolved pack (includes merged) as JSON')
    sh.add_argument('file')
    psub.add_parser('schema',help='print the JSON Schema for policy packs (for editor autocompletion)')
    args=parser.parse_args(argv)
    if args.cmd=='dev-env':
        dev_env(args.tenant,args.env_file)
    elif args.cmd=='serve':
        try:import uvicorn
        except ImportError:sys.exit("install the server extra: pip install 'recguard-kernel[server]'")
        uvicorn.run('recguard.api:from_environment',factory=True,host=args.host,port=args.port,workers=1)
    elif args.cmd=='policy':
        from .policy_pack import PackError, PolicyPack, load_pack
        if args.policy_cmd=='schema':
            print(json.dumps(PolicyPack.model_json_schema(by_alias=True),indent=2));return
        files=args.files if args.policy_cmd=='validate' else [args.file]
        failed=False
        for path in files:
            try:
                pack=load_pack(path)
                pack.validate_names()
            except (PackError,OSError) as exc:
                failed=True
                print(f'✗ {path}: {exc}',file=sys.stderr)
                continue
            if args.policy_cmd=='show':
                print(json.dumps(pack.model_dump(mode='json',by_alias=True),indent=2))
            else:
                results=pack.run_tests()
                bad=[r for r in results if not r['passed']]
                failed|=bool(bad)
                mark='✗' if bad else '✓'
                print(f'{mark} {path}: pack {pack.name!r}, {len(pack.policies)} policies, {len(pack.checks)} checks, '
                      f'context {pack.context or "none"}, tests {len(results)-len(bad)}/{len(results)} passed, digest {pack.digest[:12]}')
                for r in bad:
                    print(f'    ✗ test {r["name"]!r}: expected {r["expected"]!r}, got {r["got"]!r}',file=sys.stderr)
        sys.exit(1 if failed else 0)
    elif args.cmd=='audit':
        key=os.environ.get('RECGUARD_SIGNING_KEY')
        if not key:sys.exit('RECGUARD_SIGNING_KEY is required')
        from .storage import Store
        result=Store(args.db,key.encode()).audit_verify(args.tenant,args.expected_head)
        print(json.dumps(result));sys.exit(0 if result['valid'] else 1)


if __name__=='__main__':
    main()
